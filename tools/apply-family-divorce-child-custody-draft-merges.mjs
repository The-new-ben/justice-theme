function insertAfter(text, anchor, addition) {
  const marker = `${anchor}\n`;
  if (!text.includes(marker)) {
    throw new Error(`Anchor not found: ${anchor}`);
  }
  if (text.includes(addition)) {
    return text;
  }
  return text.replace(marker, `${marker}\n${addition}\n`);
}

